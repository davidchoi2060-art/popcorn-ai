"""개인정보 가림의 단일 원천 -- 주민번호·카드번호·전화번호·이메일·계좌번호.

근거: 2026-11-18 사장님 승인, 개인정보처리방침(2026-11-23 시행) -- 「AI 사업자로 보내기 전
전화번호·이메일 등을 가린다」를 모든 경로에 맞춘다.

■ 왜 여기 하나인가
  예전에는 같은 일을 세 벌이 따로 했다 -- `talk.mask_pii`(저장 전: 주민·전화·이메일·계좌),
  `talk_exceptions.mask_personal`(기본 상담: 주민·카드만), `talk_agent.mask`(도구 상담·PC 구성:
  주민·카드·전화·이메일). 경로마다 가리는 범위가 달라 기본 상담은 전화·이메일을 AI 사업자에게
  그대로 보냈다. 가장 넓은 `mask_pii` 표를 정본으로 옮기고 카드번호를 더해, 셋 모두 이 함수를
  부른다. `api/llm.py` 도 고객 호출(customer_facing=True)의 프롬프트를 보내기 직전에 이 함수로
  한 번 더 가린다(빠지는 호출부가 없게 -- `llm._mask_outgoing`).

■ 표시
  저장 전 가림이 써 오던 이름표 그대로다([주민번호]·[카드번호]·[전화번호]·[이메일]·[계좌번호]).
  이름표에는 숫자·@ 가 없어 두 번 가려도 바뀌지 않는다(멱등) -- 호출부와 llm.py 가 겹쳐 불러도 된다.

■ 오탐을 줄인 자리
  - 숫자 앞뒤 경계(`(?<!\\d)`·`(?!\\d)`)를 둔다. 상품 코드·바코드처럼 긴 숫자 안의 일부를
    전화번호로 오인하지 않는다.
  - 계좌는 «하이픈이 있는 것만» 본다. `\\d{10,16}` 같은 순수 숫자 패턴을 쓰면 「12000000원」
    같은 예산 표기를 계좌로 오인해 고객이 말한 조건을 지운다(옛 `mask_pii` 주석과 같은 판단).
  - 날짜(「2026-11-18」)는 계좌로 보지 않는다. 옛 `mask_pii` 는 날짜를 [계좌번호]로 지웠는데,
    AI 로 가는 상품 자료(확인 시각 등)에 날짜가 많아 그대로 쓰면 답이 망가진다.
"""
from __future__ import annotations

import re

_MASKS: tuple[tuple[re.Pattern, str], ...] = (
    # 주민·외국인등록번호(뒷자리 첫 숫자 1~8)
    (re.compile(r"(?<!\d)\d{6}\s*-\s*[1-8]\d{6}(?!\d)"), "[주민번호]"),
    # 카드번호 16자리(4자리씩, 띄어쓰기·하이픈 있거나 없거나) -- 계좌·전화보다 먼저 본다
    (re.compile(r"(?<!\d)\d{4}(?:[\s-]?\d{4}){3}(?!\d)"), "[카드번호]"),
    # 휴대전화(구분자 없어도)
    (re.compile(r"(?<!\d)01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)"), "[전화번호]"),
    # 지역번호 유선(구분자가 있을 때만)
    (re.compile(r"(?<!\d)0\d{1,2}[-.\s]\d{3,4}[-.\s]\d{4}(?!\d)"), "[전화번호]"),
    # 이메일(주소 부분은 ASCII 만 -- 「a@b.co로」의 조사까지 먹지 않게)
    (re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+"), "[이메일]"),
    # 계좌번호(하이픈 셋 묶음, 날짜 모양 제외)
    (re.compile(r"(?<![\d-])(?!(?:19|20)\d{2}-\d{1,2}-\d{1,2}(?![\d-]))\d{2,6}-\d{2,6}-\d{2,7}(?![\d-])"),
     "[계좌번호]"),
)

LABELS: tuple[str, ...] = tuple(dict.fromkeys(rep for _, rep in _MASKS))


def mask(text: str | None) -> tuple[str, bool]:
    """개인정보로 보이는 조각을 이름표로 바꾼다 -> (가린 문장, 가렸는가). 실패하지 않는다."""
    t = text or ""
    out = t
    for pat, rep in _MASKS:
        out = pat.sub(rep, out)
    return out, out != t


def has_label(text: str | None) -> bool:
    """서버가 이미 가린 자리(이름표)가 들어 있는가."""
    t = text or ""
    return any(lab in t for lab in LABELS)
