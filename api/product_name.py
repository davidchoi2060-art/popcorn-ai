# 실측된 꼬리 17종이 전부 이 한 낱말로 시작한다('회원가입시', '회원가입 구입시' 포함).
# `\[?` — 2026-08-16: 대괄호로 감싼 새 형태에서 여는 대괄호가 "회원가입" 바로 앞에 붙어
# 있으면 그 대괄호(와 앞의 공백)도 함께 걷는다. 바로 앞이 아니면(다른 글자가 끼어 있으면)
# 손대지 않는다 — 정당한 상품명 대괄호까지 지우지 않기 위해서다(위 개정 노트 참조).
_TAIL = re.compile(r"\s*\[?\s*회원가입.*$")

# 자른 뒤 이보다 짧아지면 이름 구실을 못 한다고 본다(실측 최단 유효 이름은 9자).
_MIN_LEN = 4


def display_name(raw):
    """HTML 마크업을 벗기고 판매조건 꼬리를 걷어낸 견적 표시용 이름. 못 걷으면 원천을 그대로 돌려준다."""
    if not raw:
        return raw
    # 태그를 먼저 벗긴다 — "회원가입"이 <font>…</font> 처럼 태그로 감싸인 경우(111497)도
    # 순수 텍스트로 만든 뒤에야 _TAIL 이 온전히 찾는다(위 2026-08-27 개정 노트 참조).
    stripped = strip_html_display(raw)
    cut = _TAIL.sub("", stripped).strip()
    return cut if len(cut) >= _MIN_LEN else raw
